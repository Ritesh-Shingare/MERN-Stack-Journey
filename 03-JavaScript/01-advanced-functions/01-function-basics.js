const calculateArea = (length, width) => {
  return length * width;
};
console.log("calculateArea", calculateArea(10, 5));

// isEven()
const isEven = (number) => {
  return number % 2 === 0;
};
console.log("7", isEven(7));

// calculateTotal()
const calculateTotal = (price, quantity) => {
  return price * quantity;
};
console.log("calculateTotal", calculateTotal(100, 10));
